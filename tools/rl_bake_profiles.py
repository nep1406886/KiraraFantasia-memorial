def translate_detail(ja: str) -> str:
    out = ja
    # longest source first: 「敵単体」に炎属性の大ダメージ must be consumed
    # before the bare の大ダメージ phrase leaves kana behind
    for src, dst in sorted(DETAIL_PHRASES, key=lambda p: -len(p[0])):
        out = out.replace(src, dst)
    return out


# Universal Chinese names where the wiki's characterZh left kana or an odd
# rendering in place. Include the old baked spelling so refreshing is idempotent.
NAME_FIX = {
    "後藤 ひとり": "后藤 一里",
    "后藤一里": "后藤 一里",
}


def normalize_card_name(card):
    fixed = NAME_FIX.get(card.get("characterZh"))
    if not fixed:
        return
    card["characterZh"] = fixed
    name = card.get("nameZh") or ""
    if name in NAME_FIX or name == card.get("name") or "ひとり" in name:
        card["nameZh"] = fixed


def main() -> None:
    cards_doc = load(os.path.join(OUT, "cards-rl.json"))
    skills_doc = load(os.path.join(OUT, "skills-rl.json"))

    # normal attacks: shared by all classes, so bake once outside the loop
    for row in (skills_doc.get("normalAttacks") or {}).values():
        if not row.get("nameZh"):
            row["nameZh"] = "通常攻击"
        if row.get("detail") and not row.get("detailZh"):
            row["detailZh"] = translate_detail(row["detail"])

    named = load(os.path.join(OUT, "_raw", "NamedList.json"))
    cards = cards_doc["cards"]
    for card in cards:
        normalize_card_name(card)
    by_id = {c["id"]: c for c in cards}
    named_by_char = {}
    for row in named:
        card = by_id.get(row.get("primaryCharacterID"))
        if card:
            named_by_char.setdefault(card["characterZh"], row)

    profiled = 0
    for card in cards:
        zh = PROFILE_ZH.get(card["characterZh"])
        if zh:
            card["profileZh"] = zh
            profiled += 1
            row = named_by_char.get(card["characterZh"])
            if row and row.get("m_CVText"):
                card["cv"] = row["m_CVText"]
        card["classZh"] = CLASS_ZH[card["class"]] if 0 <= card["class"] < 5 else ""
        card["elementZh"] = ELEMENT_ZH[card["element"]] if 0 <= card["element"] < 6 else ""
    print("profiles baked on %d of %d cards" % (profiled, len(cards)))

    # The wiki's characterZh carries the Japanese middle dot U+30FB
    # (アリス・カタレット), which sits inside the kana block the roster gate
    # scans for untranslated leakage — and Chinese convention is U+00B7
    # anyway. Normalized here, AFTER the profile join: the PROFILE_ZH keys
    # stay in the raw ・ spelling the data arrives in.
    for card in cards:
        if "・" in card["characterZh"]:
            card["characterZh"] = card["characterZh"].replace("・", "·")
            if card.get("nameZh") and "・" in card["nameZh"]:
                card["nameZh"] = card["nameZh"].replace("・", "·")

    # skills: bake nameZh/detailZh only for ids we authored (the designed
    # roster + its playable variants share ids; the rest keep the Japanese)
    player = skills_doc["player"]
    named_skills = 0
    det_ok = det_miss = 0
    for sid, zh in SKILL_NAME_ZH.items():
        row = player.get(str(sid)) or player.get(sid)
        if not row:
            print("WARN: skill %d not in table" % sid)
            continue
        row["nameZh"] = zh
        named_skills += 1
        if row.get("detail"):
            ja = row["detail"]
            zh_det = translate_detail(ja)
            # residual kana means an untranslated fragment: keep Japanese
            # rather than shipping a half-translated line
            residual = any("぀" <= ch <= "ゟ" for ch in zh_det)
            if residual:
                det_miss += 1
                if det_miss <= 5:
                    print("WARN: untranslated fragment in %d: %r" % (sid, zh_det))
            else:
                row["detailZh"] = zh_det
                det_ok += 1
    print("skills: %d named, %d details translated, %d kept Japanese"
          % (named_skills, det_ok, det_miss))

    save(os.path.join(OUT, "cards-rl.json"), cards_doc)
    save(os.path.join(OUT, "skills-rl.json"), skills_doc)


if __name__ == "__main__":
    main()
